#!/usr/bin/env bash
# Mutation sweep for the VEC-616 register migration.
#
# Breaks one thing at a time in 20260915_120000_secstore_registers_and_id_vocabularies.sql,
# runs the register tests, and records whether anything noticed. A mutation that SURVIVES is a
# behaviour nothing is testing.
#
# SUPERSEDED BY #984. That PR (VEC-786) builds the real harness in ../mutation/ — mutate.py
# emits mutations as JSON line-patches with stable ids, run.sh applies them in a scratch
# worktree. This is the same idea with sed and no dependencies, written because #984 has not
# landed and the evidence should not live only in a review comment. Folding in is mechanical:
# add this file to mutate.py's FILE list, add the operators below to the matching families
# (read_order, tiebreak, read_window, guard, constraint), widen run.sh's TEST_PATTERN, and
# delete this directory.
#
# Usage: ./run.sh            # full sweep, rewrites RESULTS.md
#        ./run.sh M003       # one mutation, leaves RESULTS.md alone
#
# Needs Docker (testcontainers starts timescale/timescaledb:2.29.2-pg18) and go 1.26+.

set -eo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../../../.." && pwd)"
MIG="$ROOT/stl-verify/db/migrations/20260915_120000_secstore_registers_and_id_vocabularies.sql"
RESULTS="$HERE/RESULTS.md"
BACKUP="$(mktemp)"
# TestRegister (no trailing s) so TestRegisterReads* is included too — with 'TestRegisters'
# the valid-time bound test never ran and its mutation reported a false survivor.
TESTS='TestInstrumentRegister|TestAliasRegister|TestRegister'

cp "$MIG" "$BACKUP"
restore() { cp "$BACKUP" "$MIG"; }
trap 'restore; rm -f "$BACKUP"' EXIT

# id | family | what it breaks
CATALOGUE=(
  "M001|read_order|processing_version DESC becomes ASC"
  "M002|read_order|processing_version DESC dropped from the resolution order"
  "M003|tiebreak|ingest_xid DESC dropped from the resolution order"
  "M004|tiebreak|record_id DESC dropped from the resolution order"
  "M005|read_window|as-of lower bound tightened from <= to <"
  "M006|guard|the namespace guard never raises"
  "M007|guard|the supersession guard returns before its check"
  "M008|constraint|the supersede-once unique indexes are dropped"
  "M009|guard|the approval check never raises"
)

apply() {
  case "$1" in
    M001) sed -i '' 's/processing_version DESC, ingest_xid DESC, record_id DESC/processing_version ASC, ingest_xid DESC, record_id DESC/g' "$MIG" ;;
    M002) sed -i '' 's/processing_version DESC, ingest_xid DESC, record_id DESC/ingest_xid DESC, record_id DESC/g' "$MIG" ;;
    M003) sed -i '' 's/processing_version DESC, ingest_xid DESC, record_id DESC/processing_version DESC, record_id DESC/g' "$MIG" ;;
    M004) sed -i '' 's/processing_version DESC, ingest_xid DESC, record_id DESC/processing_version DESC, ingest_xid DESC/g' "$MIG" ;;
    M005) sed -i '' 's/valid_from <= effective_at/valid_from < effective_at/g' "$MIG" ;;
    M006) sed -i '' 's/IF other_namespace IS NOT NULL THEN/IF false THEN/' "$MIG" ;;
    M007) sed -i '' 's/    IF clash IS NULL THEN/    IF true THEN/' "$MIG" ;;
    M008) sed -i '' -E 's/^CREATE UNIQUE INDEX (instrument_register|alias_register)_supersedes_once_idx/CREATE INDEX \1_supersedes_once_idx/' "$MIG" ;;
    M009) sed -i '' 's/    IF coalesce(needs_approval, false) THEN/    IF false THEN/' "$MIG" ;;
    *) echo "unknown mutation $1" >&2; exit 2 ;;
  esac
}

run_tests() {
  (cd "$ROOT/stl-verify" && go test -tags integration -count=1 -timeout 600s -run "$TESTS" ./db/migrator/... 2>&1)
}

sweep_one() {
  local id="$1" desc="$2" out killer
  restore
  apply "$id"
  if ! grep -q . "$MIG"; then echo "$id: migration emptied — bad sed" >&2; exit 2; fi
  if out=$(run_tests); then
    echo "SURVIVED||$id|$desc|—"
  else
    killer=$(echo "$out" | grep -oE '^--- FAIL: [A-Za-z]+' | head -1 | sed 's/--- FAIL: //')
    echo "killed||$id|$desc|${killer:-unknown}"
  fi
}

if [[ -n "$1" ]]; then
  for row in "${CATALOGUE[@]}"; do
    IFS='|' read -r id family desc <<< "$row"
    [[ "$id" == "$1" ]] && sweep_one "$id" "$desc"
  done
  exit 0
fi

echo "sweeping ${#CATALOGUE[@]} mutations over $(basename "$MIG")"
lines=()
survivors=0
for row in "${CATALOGUE[@]}"; do
  IFS='|' read -r id family desc <<< "$row"
  result=$(sweep_one "$id" "$desc")
  IFS='|' read -r verdict _ rid rdesc killer <<< "$result"
  [[ "$verdict" == "SURVIVED" ]] && survivors=$((survivors + 1))
  printf '  %-9s %s  %s\n' "$verdict" "$rid" "$rdesc"
  lines+=("| $rid | $family | $rdesc | $verdict | $killer |")
done

{
  echo "# Mutation results — VEC-616 registers"
  echo
  echo "Generated by \`run.sh\` against \`20260915_120000_secstore_registers_and_id_vocabularies.sql\`."
  echo "Committed rather than gitignored: a sweep whose output is not in the tree cannot be"
  echo "checked by a reviewer, which is the whole value of running it."
  echo
  echo "**$(( ${#CATALOGUE[@]} - survivors )) of ${#CATALOGUE[@]} killed.**"
  echo
  echo "| id | family | mutation | verdict | killed by |"
  echo "|---|---|---|---|---|"
  printf '%s\n' "${lines[@]}"
} > "$RESULTS"

echo
echo "wrote $RESULTS ($(( ${#CATALOGUE[@]} - survivors ))/${#CATALOGUE[@]} killed)"
[[ $survivors -eq 0 ]] || echo "WARNING: $survivors survived — those behaviours are untested"
